module osd_field_sel(
    input  wire [5:0] idx,
    input  wire [23:0] f_aud, // 4 个字符码，[5:0] 为最左字符
    input  wire [11:0] f_bri, // 2 个字符码，[5:0] 为最左字符
    input  wire [11:0] f_cd, // 2 个字符码，[5:0] 为最左字符
    input  wire [23:0] f_disp, // 4 个字符码，[5:0] 为最左字符
    input  wire [11:0] f_err, // 2 个字符码，[5:0] 为最左字符
    input  wire [5:0] f_id, // 1 个字符码，[5:0] 为最左字符
    input  wire [23:0] f_mode, // 4 个字符码，[5:0] 为最左字符
    input  wire [11:0] f_pc, // 2 个字符码，[5:0] 为最左字符
    input  wire [11:0] f_per, // 2 个字符码，[5:0] 为最左字符
    input  wire [5:0] f_sel, // 1 个字符码，[5:0] 为最左字符
    input  wire [17:0] f_src, // 3 个字符码，[5:0] 为最左字符
    input  wire [11:0] f_vol, // 2 个字符码，[5:0] 为最左字符
    output reg  [5:0] code
);
    always @(*) begin
        case(idx)
            6'd0: code=f_aud[5:0];
            6'd1: code=f_aud[11:6];
            6'd2: code=f_aud[17:12];
            6'd3: code=f_aud[23:18];
            6'd4: code=f_disp[5:0];
            6'd5: code=f_disp[11:6];
            6'd6: code=f_disp[17:12];
            6'd7: code=f_disp[23:18];
            6'd8: code=f_mode[5:0];
            6'd9: code=f_mode[11:6];
            6'd10: code=f_mode[17:12];
            6'd11: code=f_mode[23:18];
            6'd12: code=f_src[5:0];
            6'd13: code=f_src[11:6];
            6'd14: code=f_src[17:12];
            6'd15: code=f_sel[5:0];
            6'd16: code=f_bri[5:0];
            6'd17: code=f_bri[11:6];
            6'd18: code=f_cd[5:0];
            6'd19: code=f_cd[11:6];
